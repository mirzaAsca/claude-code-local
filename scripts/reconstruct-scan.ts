const unresolvedRuntime = {
  version: 1,
  generatedAt: now,
  status: 'not_implemented',
  unresolved: [],
  note: 'Scanner implementation is pending Item 2.1 in specs.md.'
};

const unresolvedTypes = {
  version: 1,
  generatedAt: now,
  status: 'not_implemented',
  unresolved: [],
  note: 'Type import scanning is pending Item 2.1 in specs.md.'
};

const summary = {
  version: 1,
  generatedAt: now,
  status: 'scaffold_only',
  runtimeMisses: 0,
  typeMisses: 0,
  note: 'Generated by scaffold script. Replace with real scan logic before treating as authoritative.'
};

writeFileSync(path.join(reportsDir, 'unresolved-runtime.json'), `${JSON.stringify(unresolvedRuntime, null, 2)}\n`);
writeFileSync(path.join(reportsDir, 'unresolved-types.json'), `${JSON.stringify(unresolvedTypes, null, 2)}\n`);
writeFileSync(path.join(reportsDir, 'scan-summary.json'), `${JSON.stringify(summary, null, 2)}\n`);

console.log(`Wrote scaffold scan reports to ${reportsDir}`);
