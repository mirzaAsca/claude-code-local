export type SourceEntry = {
  modulePath: string
  sourceKind: ManifestEntrySourceKind
  sourceRef: string
  content: string
}

/**
 * Scan reconstruction/sources/ for manually placed recovery files.
 * Each file's relative path from sources/ maps to the module path.
 */
export function loadRecoverySources(rootDir: string): Map<string, SourceEntry> {
  const sourcesDir = path.join(rootDir, 'reconstruction', 'sources')
  const entries = new Map<string, SourceEntry>()

  if (!existsSync(sourcesDir)) return entries

  function walk(dir: string): void {
    const items = readdirSync(dir, { withFileTypes: true })
    for (const item of items) {
      const fullPath = path.join(dir, item.name)
      if (item.isDirectory()) {
        walk(fullPath)
      } else if (item.isFile()) {
        const relPath = path.relative(sourcesDir, fullPath).replace(/\\/g, '/')
        entries.set(relPath, {
          modulePath: relPath,
          sourceKind: 'manual-adapted',
          sourceRef: `reconstruction/sources/${relPath}`,
          content: readFileSync(fullPath, 'utf8'),
        })
      }
    }
  }

  walk(sourcesDir)
  return entries
}

