const PROVENANCE_HEADER_TS = (modulePath: string) =>
  `// ============================================================================
// RECONSTRUCTION STUB — auto-generated by reconstruct-hydrate
// source: auto-stub
// module: ${modulePath}
// status: stubbed
// retrievedAt: ${new Date().toISOString()}
// transform: auto-generated stub — not recovered from any source
// NOTE: This file compiles but throws at runtime. Replace with recovered
//       implementation when a public source becomes available.
// ============================================================================
`

const PROVENANCE_HEADER_DTS = (modulePath: string) =>
  `// ============================================================================
// RECONSTRUCTION STUB (declaration) — auto-generated by reconstruct-hydrate
// source: auto-stub
// module: ${modulePath}
// status: stubbed
// retrievedAt: ${new Date().toISOString()}
// ============================================================================
`

const PROVENANCE_HEADER_MD = (modulePath: string) =>
  `<!-- reconstruction stub: auto-generated by reconstruct-hydrate -->
<!-- module: ${modulePath} -->
<!-- status: stubbed -->
`

const STUB_RUNTIME_ERROR = (modulePath: string) =>
  `  throw new Error(
    '[reconstruction] Module "${modulePath}" is a stub. ' +
    'It has not been recovered from any public source. ' +
    'See reconstruction/manifest.json for details.',
  )`

// ---------------------------------------------------------------------------
// Callsite analysis — extract expected exports from importer source
// ---------------------------------------------------------------------------

type ExportSpec = {
  name: string
  isType: boolean
  isDefault: boolean
}

/**
 * Analyze importer files to determine what named exports a missing module
 * must provide. Parses import statements that reference the given specifier.
 */
export function analyzeExpectedExports(
  rootDir: string,
  unresolved: UnresolvedImport[],
): ExportSpec[] {
  const exports: ExportSpec[] = []
  const seen = new Set<string>()

  for (const entry of unresolved) {
    const importerAbsPath = path.join(rootDir, entry.importer)
    let content: string
    try {
      content = readFileSync(importerAbsPath, 'utf8')
    } catch {
      continue
    }

    const specLiteral = entry.specifier.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

    // import { X, Y } from '...'  or  import type { X } from '...'
    const namedImportRe = new RegExp(
      `\\bimport\\s+(type\\s+)?\\{([^}]+)\\}\\s+from\\s*['"]${specLiteral}['"]`,
      'g',
    )
    for (const match of content.matchAll(namedImportRe)) {
      const isTypeImport = Boolean(match[1])
      const clause = match[2]
      for (const part of clause.split(',')) {
        const trimmed = part.trim()
        if (!trimmed) continue
        const isTypeSpecifier = trimmed.startsWith('type ')
        const name = (isTypeSpecifier ? trimmed.slice(5) : trimmed)
          .split(/\s+as\s+/)[0]
          .trim()
        if (name && !seen.has(name)) {
          seen.add(name)
          exports.push({ name, isType: isTypeImport || isTypeSpecifier, isDefault: false })
        }
      }
    }

    // import Default from '...'
    const defaultImportRe = new RegExp(
      `\\bimport\\s+([A-Z_$][\\w$]*)\\s+from\\s*['"]${specLiteral}['"]`,
      'g',
    )
    for (const match of content.matchAll(defaultImportRe)) {
      const name = match[1]
      if (name !== 'type' && !seen.has('default')) {
        seen.add('default')
        exports.push({ name, isType: false, isDefault: true })
      }
    }

    // export * from '...' — wildcard re-export, nothing to stub specifically
    // export { X } from '...'
    const reExportRe = new RegExp(
      `\\bexport\\s+(type\\s+)?\\{([^}]+)\\}\\s+from\\s*['"]${specLiteral}['"]`,
      'g',
    )
    for (const match of content.matchAll(reExportRe)) {
      const isTypeExport = Boolean(match[1])
      const clause = match[2]
      for (const part of clause.split(',')) {
        const trimmed = part.trim()
        if (!trimmed) continue
        const isTypeSpecifier = trimmed.startsWith('type ')
        const name = (isTypeSpecifier ? trimmed.slice(5) : trimmed)
          .split(/\s+as\s+/)[0]
          .trim()
        if (name && !seen.has(name)) {
          seen.add(name)
          exports.push({ name, isType: isTypeExport || isTypeSpecifier, isDefault: false })
        }
      }
    }

    // export * from '...'
    const wildcardReExportRe = new RegExp(
      `\\bexport\\s+\\*\\s+from\\s*['"]${specLiteral}['"]`,
      'g',
    )
    for (const _match of content.matchAll(wildcardReExportRe)) {
      // Wildcard re-exports: we generate an empty module so `export *` works
      // without errors. If specific symbols are needed they'd be caught by
      // downstream importers in a subsequent scan pass.
      void _match
    }
  }

  return exports
}

// ---------------------------------------------------------------------------
// Stub generators
// ---------------------------------------------------------------------------

function generateTsStub(modulePath: string, exports: ExportSpec[]): string {
  const lines: string[] = [PROVENANCE_HEADER_TS(modulePath)]

  const runtimeError = STUB_RUNTIME_ERROR(modulePath)

  // Type-only exports — export as empty type aliases
  const typeExports = exports.filter((e) => e.isType && !e.isDefault)
  for (const exp of typeExports) {
    lines.push(`export type ${exp.name} = Record<string, never>\n`)
  }

  // Default export
  const defaultExport = exports.find((e) => e.isDefault)
  if (defaultExport) {
    lines.push(`export default function ${defaultExport.name}(..._args: unknown[]): never {`)
    lines.push(runtimeError)
    lines.push(`}\n`)
  }

  // Named runtime exports — export as functions that throw
  const runtimeExports = exports.filter((e) => !e.isType && !e.isDefault)
  for (const exp of runtimeExports) {
    lines.push(`export function ${exp.name}(..._args: unknown[]): never {`)
    lines.push(runtimeError)
    lines.push(`}\n`)
  }

  // If no exports were detected (dynamic import or wildcard re-export),
  // generate a minimal stub with a side-effect throw guard
  if (exports.length === 0) {
    lines.push(
      `// No specific exports detected — stub for dynamic import or wildcard re-export`,
    )
    lines.push(`export {}`)
    lines.push(``)
  }

  return lines.join('\n')
}

function generateDtsStub(modulePath: string): string {
  return `${PROVENANCE_HEADER_DTS(modulePath)}
export {}
`
}

function generateMdStub(modulePath: string): string {
  return `${PROVENANCE_HEADER_MD(modulePath)}
# ${path.basename(modulePath, path.extname(modulePath))}

> This file is a reconstruction stub. The original content was not available
> from any public source at the time of hydration.
`
}

function generateJsxStub(modulePath: string, exports: ExportSpec[]): string {
  // JSX stubs are essentially TS stubs — Bun handles .jsx natively
  return generateTsStub(modulePath, exports)
}

