// Main hydration logic
// ---------------------------------------------------------------------------

export type HydrationResult = {
  manifest: Manifest
  generated: number
  recovered: number
  skippedExisting: number
  preScanRuntimeMisses: number
  postScanRuntimeMisses: number
  deltaReport: {
    resolvedByHydration: string[]
    stillUnresolved: string[]
  }
}

export function runHydrate(rootDir: string = process.cwd()): HydrationResult {
  const now = new Date().toISOString()
  const reconstructionDir = path.join(rootDir, 'reconstruction')
  const manifestPath = path.join(reconstructionDir, 'manifest.json')

  // Ensure directories exist
  mkdirSync(reconstructionDir, { recursive: true })
  mkdirSync(path.join(reconstructionDir, 'sources'), { recursive: true })
  mkdirSync(path.join(reconstructionDir, 'reports'), { recursive: true })

  // Step 1: Run pre-hydration scan to discover unresolved imports
  console.log('Running pre-hydration scan...')
  const preScan = runScan(rootDir)
  const preScanRuntimeMisses = preScan.scan.unresolvedRuntime.length

  // Step 2: Load recovery sources from reconstruction/sources/
  const recoverySources = loadRecoverySources(rootDir)

  // Step 3: Group unresolved imports by expected module path
  const allUnresolved = [
    ...preScan.scan.unresolvedRuntime,
    ...preScan.scan.unresolvedTypes,
  ]
  const moduleGroups = new Map<string, UnresolvedImport[]>()
  for (const entry of allUnresolved) {
    const key = entry.expectedModulePath
    if (!moduleGroups.has(key)) moduleGroups.set(key, [])
    moduleGroups.get(key)!.push(entry)
  }

  // Step 4: Generate stubs or apply recovered sources
  const entries: ManifestEntry[] = []
  let generated = 0
  let recovered = 0
  let skippedExisting = 0

  // Load existing manifest to preserve manually-set entries
  const existingEntries = new Map<string, ManifestEntry>()
  try {
    const existing = JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest
    if (Array.isArray(existing.entries)) {
      for (const e of existing.entries) {
        if (typeof e.modulePath === 'string') {
          existingEntries.set(e.modulePath, e as ManifestEntry)
        }
      }
    }
  } catch { /* no existing manifest */ }

  for (const [modulePath, refs] of moduleGroups) {
    const absPath = path.join(rootDir, modulePath)

    // Skip if file already exists on disk (previously recovered or hand-written)
    if (existsSync(absPath)) {
      const existing = existingEntries.get(modulePath)
      if (existing) entries.push(existing)
      skippedExisting++
      continue
    }

    // Check if we have a recovery source
    const recoverySource = recoverySources.get(modulePath)
    if (recoverySource) {
      mkdirSync(path.dirname(absPath), { recursive: true })
      writeFileSync(absPath, recoverySource.content)
      const hash = createHash('sha256').update(recoverySource.content).digest('hex').slice(0, 16)
      entries.push({
        modulePath,
        status: 'recovered_adapted',
        sourceKind: recoverySource.sourceKind,
        sourceRef: recoverySource.sourceRef,
        hash,
        updatedAt: now,
        owner: 'reconstruct-hydrate',
      })
      recovered++
      continue
    }

    // Generate a stub based on file extension
    const ext = path.extname(modulePath)
    let content: string

    if (ext === '.md') {
      content = generateMdStub(modulePath)
    } else if (modulePath.endsWith('.d.ts')) {
      content = generateDtsStub(modulePath)
    } else if (ext === '.jsx') {
      const expectedExports = analyzeExpectedExports(rootDir, refs)
      content = generateJsxStub(modulePath, expectedExports)
    } else {
      // .ts, .tsx, or other — analyze callsites for expected exports
      const expectedExports = analyzeExpectedExports(rootDir, refs)
      content = generateTsStub(modulePath, expectedExports)
    }

    mkdirSync(path.dirname(absPath), { recursive: true })
    writeFileSync(absPath, content)

    const hash = createHash('sha256').update(content).digest('hex').slice(0, 16)
    entries.push({
      modulePath,
      status: 'stubbed',
      sourceKind: 'auto-stub',
      sourceRef: 'reconstruct-hydrate auto-generated',
      hash,
      updatedAt: now,
      owner: 'reconstruct-hydrate',
    })
    generated++
  }

  // Step 5: Sort entries deterministically by modulePath
  entries.sort((a, b) => a.modulePath.localeCompare(b.modulePath))

  // Collect all unresolved import keys for the baseline
  const unresolvedRuntimeBaseline = preScan.scan.unresolvedRuntime
    .map((u) => u.key)
    .sort()

  // Step 6: Write manifest
  const manifest: Manifest = {
    version: 1,
    updatedAt: now,
    status: 'active',
    note: 'Generated by reconstruct-hydrate. Per-module status tracks recovery progress.',
    unresolvedRuntimeBaseline,
    entries,
  }

  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`)

  // Step 7: Re-run scan to measure post-hydration state
  console.log('Running post-hydration scan...')
  const postScan = runScan(rootDir)
  const postScanRuntimeMisses = postScan.scan.unresolvedRuntime.length

  // Step 8: Compute delta report
  const preModules = new Set(
    preScan.scan.unresolvedRuntime.map((u) => u.expectedModulePath),
  )
  const postModules = new Set(
    postScan.scan.unresolvedRuntime.map((u) => u.expectedModulePath),
  )

  const resolvedByHydration = [...preModules]
    .filter((m) => !postModules.has(m))
    .sort()
  const stillUnresolved = [...postModules].sort()

  const deltaReport = {
    version: 1,
    generatedAt: now,
    preScanRuntimeMisses,
    postScanRuntimeMisses,
    resolvedModuleCount: resolvedByHydration.length,
    stillUnresolvedModuleCount: stillUnresolved.length,
    resolvedByHydration,
    stillUnresolved,
  }

  writeFileSync(
    path.join(reconstructionDir, 'reports', 'hydration-delta.json'),
    `${JSON.stringify(deltaReport, null, 2)}\n`,
  )

  return {
    manifest,
    generated,
    recovered,
    skippedExisting,
    preScanRuntimeMisses,
    postScanRuntimeMisses,
    deltaReport: { resolvedByHydration, stillUnresolved },
  }
}

// ---------------------------------------------------------------------------
// Manifest validation (spec 2.3.3)
// ---------------------------------------------------------------------------

export function validateManifestCoverage(rootDir: string): {
  valid: boolean
  missingEntries: string[]
} {
  const manifestPath = path.join(rootDir, 'reconstruction', 'manifest.json')
  if (!existsSync(manifestPath)) {
    return { valid: false, missingEntries: ['(manifest not found)'] }
  }

  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest
  const entryPaths = new Set(manifest.entries.map((e) => e.modulePath))

  // Run scan to get current unresolved imports
  const scan = runScan(rootDir)
  const unresolvedModules = new Set(
    scan.scan.unresolvedRuntime.map((u) => u.expectedModulePath),
  )

  const missingEntries = [...unresolvedModules]
    .filter((m) => !entryPaths.has(m))
    .sort()

  return { valid: missingEntries.length === 0, missingEntries }
}

