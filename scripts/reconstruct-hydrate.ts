import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'fs'
import { createHash } from 'crypto'
import path from 'path'
import { runScan, type UnresolvedImport } from './reconstruct-scan.js'

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type ManifestEntryStatus =
  | 'recovered_exact'
  | 'recovered_adapted'
  | 'stubbed'

export type ManifestEntrySourceKind =
  | 'npm-tarball'
  | 'public-repo'
  | 'manual-adapted'
  | 'auto-stub'

export type ManifestEntry = {
  modulePath: string
  status: ManifestEntryStatus
  sourceKind: ManifestEntrySourceKind
  sourceRef: string
  hash: string
  updatedAt: string
  owner: string
}

export type Manifest = {
  version: number
  updatedAt: string
  status: 'active'
  note: string
  unresolvedRuntimeBaseline: string[]
  entries: ManifestEntry[]
}

