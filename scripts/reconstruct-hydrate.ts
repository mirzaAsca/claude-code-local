// CLI entry
// ---------------------------------------------------------------------------

if (import.meta.main) {
  const result = runHydrate()

  console.log(`\nHydration complete:`)
  console.log(`  Generated stubs: ${result.generated}`)
  console.log(`  Recovered from sources: ${result.recovered}`)
  console.log(`  Skipped (already exist): ${result.skippedExisting}`)
  console.log(`  Pre-hydration runtime misses: ${result.preScanRuntimeMisses}`)
  console.log(`  Post-hydration runtime misses: ${result.postScanRuntimeMisses}`)
  console.log(`  Resolved by hydration: ${result.deltaReport.resolvedByHydration.length} modules`)

  if (result.deltaReport.stillUnresolved.length > 0) {
    console.log(`  Still unresolved: ${result.deltaReport.stillUnresolved.length} modules`)
  }

  console.log(`\nManifest written with ${result.manifest.entries.length} entries`)
}
